int test_aes_gcm64(void) {
    // Without the instructions every call below raises #UD, so this is a hard
    // precondition rather than a skip: the build has no software fallback.
    if (!aes_hardware_available()) return -1;

    u8 block[AES_BLOCK_SIZE];
    struct aes128 cipher;
    aes128_init(&cipher, fips_key);
    aes128_encrypt_block(&cipher, fips_plain, block);
    int valid = crypto_equal(block, fips_cipher, AES_BLOCK_SIZE);

    static u8 output[64];
    static u8 recovered[64];
    u8 tag[GCM_TAG_SIZE];
    struct aes128_gcm gcm;

    aes128_gcm_init(&gcm, zero_key);
    valid = valid && !aes128_gcm_seal(&gcm, zero_nonce, 0, 0, 0, 0, output, tag) &&
        crypto_equal(tag, tag_empty, GCM_TAG_SIZE);

    u8 zero_block[AES_BLOCK_SIZE];
    for (u32 index = 0; index < AES_BLOCK_SIZE; index++) zero_block[index] = 0;
    valid = valid &&
        !aes128_gcm_seal(&gcm, zero_nonce, 0, 0, zero_block, AES_BLOCK_SIZE,
                         output, tag) &&
        crypto_equal(output, ct_zero_block, AES_BLOCK_SIZE) &&
        crypto_equal(tag, tag_zero_block, GCM_TAG_SIZE);

    aes128_gcm_init(&gcm, gcm_key);
    valid = valid &&
        !aes128_gcm_seal(&gcm, gcm_nonce, 0, 0, plain_64, 64, output, tag) &&
        crypto_equal(output, cipher_64, 64) &&
        crypto_equal(tag, tag_64, GCM_TAG_SIZE) &&
        !aes128_gcm_open(&gcm, gcm_nonce, 0, 0, output, 64, tag, recovered) &&
        crypto_equal(recovered, plain_64, 64);

    // 20 bytes of AAD and 60 of plaintext: neither is a whole number of
    // blocks, so both partial-block paths of GHASH are exercised at once.
    valid = valid &&
        !aes128_gcm_seal(&gcm, gcm_nonce, aad_20, 20, plain_64, 60, output,
                         tag) &&
        crypto_equal(output, cipher_60, 60) &&
        crypto_equal(tag, tag_60, GCM_TAG_SIZE) &&
        !aes128_gcm_open(&gcm, gcm_nonce, aad_20, 20, output, 60, tag,
                         recovered) &&
        crypto_equal(recovered, plain_64, 60);

    // Every one of these has to be refused, and refusal must leave the output
    // buffer alone rather than hand back decrypted bytes.
    for (u32 index = 0; index < 64; index++) recovered[index] = 0xA5u;
    u8 broken[GCM_TAG_SIZE];
    for (u32 index = 0; index < GCM_TAG_SIZE; index++) broken[index] = tag[index];
    broken[GCM_TAG_SIZE - 1] ^= 1u;
    valid = valid &&
        aes128_gcm_open(&gcm, gcm_nonce, aad_20, 20, output, 60, broken,
                        recovered) == -1 &&
        recovered[0] == 0xA5u && recovered[59] == 0xA5u;

    broken[GCM_TAG_SIZE - 1] ^= 1u;
    broken[0] ^= 0x80u;
    valid = valid &&
        aes128_gcm_open(&gcm, gcm_nonce, aad_20, 20, output, 60, broken,
                        recovered) == -1;

    // A modified ciphertext, a modified AAD and a truncated length all change
    // the tag input, so all three have to fail.
    output[0] ^= 1u;
    valid = valid &&
        aes128_gcm_open(&gcm, gcm_nonce, aad_20, 20, output, 60, tag,
                        recovered) == -1;
    output[0] ^= 1u;

    static u8 tampered_aad[20];
    for (u32 index = 0; index < 20; index++) tampered_aad[index] = aad_20[index];
    tampered_aad[19] ^= 1u;
    valid = valid &&
        aes128_gcm_open(&gcm, gcm_nonce, aad_20, 20, output, 60, tag,
                        recovered) == 0 &&
        aes128_gcm_open(&gcm, gcm_nonce, tampered_aad, 20, output, 60, tag,
                        recovered) == -1 &&
        aes128_gcm_open(&gcm, gcm_nonce, aad_20, 20, output, 59, tag,
                        recovered) == -1;

    return valid ? 0 : -1;
}
