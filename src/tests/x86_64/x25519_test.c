int test_x25519_64(void) {
    u8 out[X25519_KEY_SIZE];
    int valid = !x25519(out, scalar_one, point_one) &&
        crypto_equal(out, expect_one, X25519_KEY_SIZE) &&
        !x25519(out, scalar_two, point_two) &&
        crypto_equal(out, expect_two, X25519_KEY_SIZE);

    // A full exchange: both sides derive their public key and then the same
    // secret from the other side's.
    u8 derived[X25519_KEY_SIZE];
    valid = valid && !x25519_base(derived, alice_private) &&
        crypto_equal(derived, alice_public, X25519_KEY_SIZE) &&
        !x25519_base(derived, bob_private) &&
        crypto_equal(derived, bob_public, X25519_KEY_SIZE);

    u8 from_alice[X25519_KEY_SIZE];
    u8 from_bob[X25519_KEY_SIZE];
    valid = valid && !x25519(from_alice, alice_private, bob_public) &&
        !x25519(from_bob, bob_private, alice_public) &&
        crypto_equal(from_alice, shared_secret, X25519_KEY_SIZE) &&
        crypto_equal(from_bob, shared_secret, X25519_KEY_SIZE);

    u8 scalar[X25519_KEY_SIZE];
    u8 point[X25519_KEY_SIZE];
    u8 next[X25519_KEY_SIZE];
    for (u32 index = 0; index < X25519_KEY_SIZE; index++) {
        scalar[index] = 0;
        point[index] = 0;
    }
    scalar[0] = 9;
    point[0] = 9;
    valid = valid && !x25519(next, scalar, point);
    for (u32 index = 0; index < X25519_KEY_SIZE; index++) {
        point[index] = scalar[index];
        scalar[index] = next[index];
    }
    valid = valid && crypto_equal(scalar, iterated_one, X25519_KEY_SIZE);

    // Small-order points drive the shared secret to zero. Accepting one would
    // let a peer force a known key, so the call has to fail.
    u8 zero_point[X25519_KEY_SIZE];
    for (u32 index = 0; index < X25519_KEY_SIZE; index++) zero_point[index] = 0;
    valid = valid && x25519(out, alice_private, zero_point) == -1 &&
        x25519(out, alice_private, low_order_one) == -1 &&
        x25519(out, alice_private, low_order_two) == -1;

    // Clamping happens inside, so an unclamped scalar and its clamped form
    // must agree. Otherwise a caller could reach the cleared low bits.
    u8 dirty[X25519_KEY_SIZE];
    u8 clean[X25519_KEY_SIZE];
    for (u32 index = 0; index < X25519_KEY_SIZE; index++) {
        dirty[index] = scalar_one[index];
        clean[index] = scalar_one[index];
    }
    clean[0] &= 248u;
    clean[31] &= 127u;
    clean[31] |= 64u;
    u8 dirty_result[X25519_KEY_SIZE];
    u8 clean_result[X25519_KEY_SIZE];
    valid = valid && !x25519(dirty_result, dirty, point_one) &&
        !x25519(clean_result, clean, point_one) &&
        crypto_equal(dirty_result, clean_result, X25519_KEY_SIZE);

    // The top bit of the u-coordinate is ignored rather than rejected.
    u8 masked_point[X25519_KEY_SIZE];
    for (u32 index = 0; index < X25519_KEY_SIZE; index++)
        masked_point[index] = point_one[index];
    masked_point[31] |= 0x80u;
    valid = valid && !x25519(out, scalar_one, masked_point) &&
        crypto_equal(out, expect_one, X25519_KEY_SIZE);

    return valid ? 0 : -1;
}
