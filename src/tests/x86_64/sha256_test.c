static void fill(u8 *buffer, u32 length, u8 value) {
    for (u32 index = 0; index < length; index++) buffer[index] = value;
}

static int digest_is(const void *data, u32 length, const u8 expected[32]) {
    u8 digest[SHA256_DIGEST_SIZE];
    sha256_digest(data, length, digest);
    return crypto_equal(digest, expected, SHA256_DIGEST_SIZE);
}

int test_sha256_64(void) {
    static u8 scratch[200];
    int valid = digest_is("", 0, digest_empty) &&
        digest_is("abc", 3, digest_abc) &&
        digest_is("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq",
                  56, digest_448) &&
        digest_is("abcdefghbcdefghicdefghijdefghijkefghijklfghijklmghijklmn"
                  "hijklmnoijklmnopjklmnopqklmnopqrlmnopqrsmnopqrstnopqrstu",
                  112, digest_896);

    // Padding boundaries: 55 bytes still fits the length field, 56 forces a
    // second block, 64 is an exact block. Hand-written padding usually breaks
    // on exactly these three.
    fill(scratch, 64, 'a');
    valid = valid && digest_is(scratch, 55, digest_55) &&
        digest_is(scratch, 56, digest_56) && digest_is(scratch, 64, digest_64);

    struct sha256 context;
    sha256_init(&context);
    fill(scratch, 100, 'a');
    for (u32 index = 0; index < 10000; index++)
        sha256_update(&context, scratch, 100);
    u8 digest[SHA256_DIGEST_SIZE];
    sha256_final(&context, digest);
    valid = valid && crypto_equal(digest, digest_million, SHA256_DIGEST_SIZE);

    // The transcript hash is read while the transcript keeps growing, so a
    // copy of the context has to finalise without disturbing the original.
    struct sha256 transcript;
    sha256_init(&transcript);
    sha256_update(&transcript, "ab", 2);
    struct sha256 snapshot = transcript;
    u8 partial[SHA256_DIGEST_SIZE];
    sha256_final(&snapshot, partial);
    u8 expected_partial[SHA256_DIGEST_SIZE];
    sha256_digest("ab", 2, expected_partial);
    sha256_update(&transcript, "c", 1);
    u8 whole[SHA256_DIGEST_SIZE];
    sha256_final(&transcript, whole);
    valid = valid &&
        crypto_equal(partial, expected_partial, SHA256_DIGEST_SIZE) &&
        crypto_equal(whole, digest_abc, SHA256_DIGEST_SIZE);

    u8 mac[SHA256_DIGEST_SIZE];
    fill(scratch, 20, 0x0B);
    hmac_sha256_digest(scratch, 20, "Hi There", 8, mac);
    valid = valid && crypto_equal(mac, mac_case1, SHA256_DIGEST_SIZE);
    hmac_sha256_digest("Jefe", 4, "what do ya want for nothing?", 28, mac);
    valid = valid && crypto_equal(mac, mac_case2, SHA256_DIGEST_SIZE);
    fill(scratch, 20, 0xAA);
    static u8 payload[50];
    fill(payload, 50, 0xDD);
    hmac_sha256_digest(scratch, 20, payload, 50, mac);
    valid = valid && crypto_equal(mac, mac_case3, SHA256_DIGEST_SIZE);

    // A key longer than the block has to be hashed down first.
    fill(scratch, 131, 0xAA);
    hmac_sha256_digest(scratch, 131,
                       "Test Using Larger Than Block-Size Key - Hash Key First",
                       54, mac);
    valid = valid && crypto_equal(mac, mac_case6, SHA256_DIGEST_SIZE);

    static u8 ikm[80];
    static u8 salt[80];
    static u8 info[80];
    static u8 okm[82];
    u8 prk[SHA256_DIGEST_SIZE];
    fill(ikm, 22, 0x0B);
    for (u32 index = 0; index < 13; index++) salt[index] = (u8)index;
    for (u32 index = 0; index < 10; index++) info[index] = (u8)(0xF0 + index);
    hkdf_sha256_extract(salt, 13, ikm, 22, prk);
    valid = valid && crypto_equal(prk, hkdf_prk_basic, SHA256_DIGEST_SIZE) &&
        !hkdf_sha256_expand(prk, info, 10, okm, 42) &&
        crypto_equal(okm, hkdf_okm_basic, 42);

    for (u32 index = 0; index < 80; index++) {
        ikm[index] = (u8)index;
        salt[index] = (u8)(0x60 + index);
        info[index] = (u8)(0xB0 + index);
    }
    hkdf_sha256_extract(salt, 80, ikm, 80, prk);
    valid = valid && crypto_equal(prk, hkdf_prk_long, SHA256_DIGEST_SIZE) &&
        !hkdf_sha256_expand(prk, info, 80, okm, 82) &&
        crypto_equal(okm, hkdf_okm_long, 82);

    // An absent salt is defined as a block of zeros, not as an error.
    fill(ikm, 22, 0x0B);
    hkdf_sha256_extract(0, 0, ikm, 22, prk);
    valid = valid && crypto_equal(prk, hkdf_prk_nosalt, SHA256_DIGEST_SIZE) &&
        !hkdf_sha256_expand(prk, 0, 0, okm, 42) &&
        crypto_equal(okm, hkdf_okm_nosalt, 42);

    // Expand counts blocks in one byte and must refuse to exceed that.
    valid = valid &&
        hkdf_sha256_expand(prk, 0, 0, okm, HKDF_SHA256_MAX_OUTPUT + 1) == -1;

    // crypto_equal has to reject a difference in any position, including the
    // last byte, which a length-only comparison would miss.
    u8 left[SHA256_DIGEST_SIZE];
    u8 right[SHA256_DIGEST_SIZE];
    fill(left, SHA256_DIGEST_SIZE, 0x5A);
    fill(right, SHA256_DIGEST_SIZE, 0x5A);
    valid = valid && crypto_equal(left, right, SHA256_DIGEST_SIZE);
    right[SHA256_DIGEST_SIZE - 1] ^= 1u;
    valid = valid && !crypto_equal(left, right, SHA256_DIGEST_SIZE);
    right[SHA256_DIGEST_SIZE - 1] ^= 1u;
    right[0] ^= 0x80u;
    valid = valid && !crypto_equal(left, right, SHA256_DIGEST_SIZE);

    crypto_zero(left, sizeof(left));
    valid = valid && !left[0] && !left[SHA256_DIGEST_SIZE - 1];

    return valid ? 0 : -1;
}
