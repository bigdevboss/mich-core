int test_rsa64(void) {
    struct rsa_public_key key;
    int valid = !rsa_public_key_init(&key, isrg_x1_modulus,
                                     sizeof(isrg_x1_modulus), 65537u) &&
        key.modulus_bytes == 512u && key.limbs == 64u &&
        !rsa_pkcs1_verify_sha256(&key, isrg_x1_tbs_digest, isrg_x1_signature,
                                 sizeof(isrg_x1_signature));

    // One bit of the signed body has to break the signature.
    u8 tampered[32];
    for (u32 index = 0; index < 32; index++)
        tampered[index] = isrg_x1_tbs_digest[index];
    tampered[0] ^= 1u;
    valid = valid && rsa_pkcs1_verify_sha256(&key, tampered, isrg_x1_signature,
                                             sizeof(isrg_x1_signature)) == -1;

    valid = valid && !rsa_public_key_init(&key, digicert_g2_modulus,
                                          sizeof(digicert_g2_modulus), 65537u) &&
        key.modulus_bytes == 256u &&
        !rsa_pkcs1_verify_sha256(&key, digicert_g2_tbs_digest,
                                 digicert_g2_signature,
                                 sizeof(digicert_g2_signature));

    // A signature is only valid under its own key: the 2048 bit root must not
    // accept the 4096 bit root's signature, whatever the lengths.
    valid = valid && rsa_pkcs1_verify_sha256(&key, isrg_x1_tbs_digest,
                                             isrg_x1_signature,
                                             sizeof(isrg_x1_signature)) == -1;

    struct rsa_public_key pss_key;
    valid = valid && !rsa_public_key_init(&pss_key, pss_modulus,
                                          sizeof(pss_modulus), 65537u) &&
        !rsa_pss_verify_sha256(&pss_key, pss_digest, pss_signature,
                               sizeof(pss_signature));

    for (u32 index = 0; index < 32; index++) tampered[index] = pss_digest[index];
    tampered[31] ^= 1u;
    valid = valid && rsa_pss_verify_sha256(&pss_key, tampered, pss_signature,
                                           sizeof(pss_signature)) == -1;

    // The two padding schemes must not accept each other's output, or a peer
    // could downgrade PSS to the weaker construction.
    valid = valid && rsa_pkcs1_verify_sha256(&pss_key, pss_digest,
                                             pss_signature,
                                             sizeof(pss_signature)) == -1;

    u8 broken_signature[256];
    for (u32 index = 0; index < sizeof(broken_signature); index++)
        broken_signature[index] = pss_signature[index];
    broken_signature[0] ^= 0x01u;
    valid = valid && rsa_pss_verify_sha256(&pss_key, pss_digest,
                                           broken_signature,
                                           sizeof(broken_signature)) == -1;

    // A signature shorter or longer than the modulus is malformed.
    valid = valid && rsa_pss_verify_sha256(&pss_key, pss_digest, pss_signature,
                                           sizeof(pss_signature) - 1u) == -1;

    // Malformed keys are refused at init rather than failing later.
    u8 even_modulus[256];
    for (u32 index = 0; index < sizeof(even_modulus); index++)
        even_modulus[index] = pss_modulus[index];
    even_modulus[sizeof(even_modulus) - 1u] &= 0xFEu;
    struct rsa_public_key rejected;
    valid = valid &&
        rsa_public_key_init(&rejected, even_modulus,
                            sizeof(even_modulus), 65537u) == -1 &&
        rsa_public_key_init(&rejected, pss_modulus, sizeof(pss_modulus),
                            65536u) == -1 &&
        rsa_public_key_init(&rejected, pss_modulus, sizeof(pss_modulus),
                            1u) == -1 &&
        rsa_public_key_init(&rejected, pss_modulus, 0u, 65537u) == -1 &&
        rsa_public_key_init(&rejected, 0, sizeof(pss_modulus), 65537u) == -1;

    return valid ? 0 : -1;
}
