// 2026-09-24, inside the validity window of every certificate above. Supplied
// rather than read from the clock so the test does not expire with them.
#define TEST_NOW 1790240000ull

int test_x509_chain64(void) {
    const u8 *chain[3] = { leaf_der, intermediate_der, cross_der };
    u32 lengths[3] = { sizeof(leaf_der), sizeof(intermediate_der),
                       sizeof(cross_der) };
    const struct x509_trust_store *store = x509_builtin_trust_store();
    int valid = store && store->count == 3u;

    valid = valid && !x509_verify_chain(chain, lengths, 2u, store,
                                        "google.com", 10u, TEST_NOW);
    // The leaf carries *.google.com, so the wildcard has to cover one label.
    valid = valid && !x509_verify_chain(chain, lengths, 2u, store,
                                        "www.google.com", 14u, TEST_NOW);
    // A server may append a cross-signed root whose own issuer is unknown to
    // this store; the chain still closes on the anchor one level below it.
    valid = valid && !x509_verify_chain(chain, lengths, 3u, store,
                                        "google.com", 10u, TEST_NOW);
    // Host matching needs no cryptography, so it is exercised directly rather
    // than by running a full chain validation for every pattern.
    struct x509_certificate leaf;
    valid = valid && !x509_parse(&leaf, leaf_der, sizeof(leaf_der)) &&
        !x509_match_host(&leaf, "google.com", 10u) &&
        !x509_match_host(&leaf, "www.google.com", 14u) &&
        !x509_match_host(&leaf, "WWW.GOOGLE.COM", 14u) &&
        !x509_match_host(&leaf, "google.com.", 11u) &&
        // A wildcard replaces exactly one label, never two, and never none.
        x509_match_host(&leaf, "a.b.google.com", 14u) == -1 &&
        x509_match_host(&leaf, "example.com", 11u) == -1 &&
        x509_match_host(&leaf, "notgoogle.com", 13u) == -1 &&
        x509_match_host(&leaf, "com", 3u) == -1 &&
        x509_match_host(&leaf, ".google.com", 11u) == -1 &&
        x509_match_host(&leaf, "", 0u) == -1;

    // Outside the validity window in either direction.
    valid = valid &&
        x509_verify_chain(chain, lengths, 2u, store, "google.com", 10u,
                          1900000000ull) == -1 &&
        x509_verify_chain(chain, lengths, 2u, store, "google.com", 10u,
                          1600000000ull) == -1;

    // A leaf alone proves nothing, and neither does a chain with a hole in it.
    const u8 *broken[2] = { leaf_der, cross_der };
    u32 broken_lengths[2] = { sizeof(leaf_der), sizeof(cross_der) };
    valid = valid &&
        x509_verify_chain(chain, lengths, 1u, store, "google.com", 10u,
                          TEST_NOW) == -1 &&
        x509_verify_chain(broken, broken_lengths, 2u, store, "google.com",
                          10u, TEST_NOW) == -1;

    valid = valid &&
        x509_verify_chain(chain, lengths, 0u, store, "google.com", 10u,
                          TEST_NOW) == -1 &&
        x509_verify_chain(chain, lengths, X509_MAX_CHAIN + 1u, store,
                          "google.com", 10u, TEST_NOW) == -1 &&
        x509_verify_chain(0, lengths, 2u, store, "google.com", 10u,
                          TEST_NOW) == -1 &&
        x509_verify_chain(chain, lengths, 2u, 0, "google.com", 10u,
                          TEST_NOW) == -1 &&
        x509_verify_chain(chain, lengths, 2u, store, 0, 10u, TEST_NOW) == -1 &&
        x509_verify_chain(chain, lengths, 2u, store, "google.com", 0u,
                          TEST_NOW) == -1;

    // One flipped bit in any position of the signed body breaks the chain.
    // One flipped bit inside the signed body has to break the chain. A single
    // position is enough: each of these runs a full RSA verification, and the
    // signature check itself is covered by its own known-answer test.
    static u8 tampered[4096];
    for (u32 index = 0; index < sizeof(leaf_der); index++)
        tampered[index] = leaf_der[index];
    tampered[sizeof(leaf_der) / 2u] ^= 0x10u;
    const u8 *mutated[2] = { tampered, intermediate_der };
    valid = valid &&
        x509_verify_chain(mutated, lengths, 2u, store, "google.com", 10u,
                          TEST_NOW) == -1;

    // An empty store cannot anchor anything, however good the chain is.
    struct x509_trust_store empty;
    empty.anchors = store->anchors;
    empty.count = 0;
    valid = valid && x509_verify_chain(chain, lengths, 2u, &empty,
                                       "google.com", 10u, TEST_NOW) == -1;

    return valid ? 0 : -1;
}
