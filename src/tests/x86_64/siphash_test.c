int test_siphash64(void) {
    u8 key[SIPHASH_KEY_SIZE];
    for (u32 index = 0; index < SIPHASH_KEY_SIZE; index++)
        key[index] = (u8)index;

    u8 message[64];
    int valid = 1;
    for (u32 length = 0; length < 64; length++) {
        message[length] = (u8)length;
        valid = valid &&
            siphash_2_4(key, message, length) == reference[length];
    }

    // A one-bit change in the key must change the output, or the key is not
    // actually binding the hash.
    key[0] ^= 1u;
    valid = valid && siphash_2_4(key, message, 8) != reference[8];

    return valid ? 0 : -1;
}
