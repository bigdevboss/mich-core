int test_tls_records64(void) {
    struct tls_key_schedule schedule;
    tls_key_schedule_init(&schedule);
    int valid = crypto_equal(schedule.early_secret, rfc_early_secret,
                             TLS_SECRET_SIZE);

    valid = valid && !tls_key_schedule_handshake(&schedule, rfc_ecdhe,
                                                 sizeof(rfc_ecdhe),
                                                 rfc_hash_after_hello) &&
        crypto_equal(schedule.handshake_secret, rfc_handshake_secret,
                     TLS_SECRET_SIZE) &&
        crypto_equal(schedule.client_handshake_traffic, rfc_client_handshake,
                     TLS_SECRET_SIZE) &&
        crypto_equal(schedule.server_handshake_traffic, rfc_server_handshake,
                     TLS_SECRET_SIZE);

    valid = valid && !tls_key_schedule_application(&schedule,
                                                   rfc_hash_after_finished) &&
        crypto_equal(schedule.master_secret, rfc_master_secret,
                     TLS_SECRET_SIZE) &&
        crypto_equal(schedule.client_application_traffic,
                     rfc_client_application, TLS_SECRET_SIZE) &&
        crypto_equal(schedule.server_application_traffic,
                     rfc_server_application, TLS_SECRET_SIZE);

    u8 key[TLS_KEY_SIZE];
    u8 iv[TLS_IV_SIZE];
    valid = valid && !tls_traffic_keys(rfc_server_handshake, key, iv) &&
        crypto_equal(key, rfc_server_key, TLS_KEY_SIZE) &&
        crypto_equal(iv, rfc_server_iv, TLS_IV_SIZE);

    // The real record the server sent, carrying EncryptedExtensions through
    // Finished. Opening it proves the nonce, the additional data and the
    // inner plaintext layout all match the specification.
    struct tls_record_context reader;
    static u8 plaintext[TLS_RECORD_MAX_CIPHERTEXT];
    u32 plaintext_length = 0;
    u8 content_type = 0;
    valid = valid && !tls_record_init(&reader, rfc_server_handshake) &&
        !tls_record_open(&reader, rfc_record, sizeof(rfc_record), plaintext,
                         &plaintext_length, &content_type) &&
        plaintext_length == sizeof(rfc_inner) &&
        crypto_equal(plaintext, rfc_inner, plaintext_length) &&
        content_type == TLS_CONTENT_HANDSHAKE &&
        reader.sequence == 1u;

    static const u8 message[22] = {
        'm', 'i', 'c', 'h', ' ', 'c', 'o', 'r', 'e', ' ', 'r', 'e',
        'c', 'o', 'r', 'd', ' ', 'l', 'a', 'y', 'e', 'r',
    };
    struct tls_record_context sender;
    struct tls_record_context receiver;
    static u8 record[TLS_RECORD_MAX_CIPHERTEXT];
    u32 record_length = 0;
    valid = valid && !tls_record_init(&sender, rfc_client_application) &&
        !tls_record_init(&receiver, rfc_client_application) &&
        !tls_record_seal(&sender, TLS_CONTENT_APPLICATION_DATA, message,
                         sizeof(message), record, &record_length) &&
        // The header always claims application data, whatever is inside.
        record[0] == TLS_CONTENT_APPLICATION_DATA &&
        !tls_record_open(&receiver, record, record_length, plaintext,
                         &plaintext_length, &content_type) &&
        plaintext_length == sizeof(message) &&
        crypto_equal(plaintext, message, sizeof(message)) &&
        content_type == TLS_CONTENT_APPLICATION_DATA;

    // A handshake record hides its type the same way.
    struct tls_record_context hidden;
    valid = valid && !tls_record_init(&hidden, rfc_client_application) &&
        !tls_record_seal(&hidden, TLS_CONTENT_HANDSHAKE, message, 4u, record,
                         &record_length) &&
        record[0] == TLS_CONTENT_APPLICATION_DATA;
    struct tls_record_context reveal;
    valid = valid && !tls_record_init(&reveal, rfc_client_application) &&
        !tls_record_open(&reveal, record, record_length, plaintext,
                         &plaintext_length, &content_type) &&
        content_type == TLS_CONTENT_HANDSHAKE;

    // Nothing a peer can change may be accepted: the tag, the ciphertext and
    // the header are all covered.
    for (u32 position = 0; position < 3u; position++) {
        struct tls_record_context broken;
        u32 index = position == 0 ? record_length - 1u
                                  : (position == 1 ? TLS_RECORD_HEADER_SIZE
                                                   : 3u);
        record[index] ^= 1u;
        valid = valid && !tls_record_init(&broken, rfc_client_application) &&
            tls_record_open(&broken, record, record_length, plaintext,
                            &plaintext_length, &content_type) == -1;
        record[index] ^= 1u;
    }

    // Two records with the same content must not produce the same bytes: the
    // sequence number has to reach the nonce.
    struct tls_record_context repeated;
    static u8 first[64];
    static u8 second[64];
    u32 first_length = 0;
    u32 second_length = 0;
    valid = valid && !tls_record_init(&repeated, rfc_client_application) &&
        !tls_record_seal(&repeated, TLS_CONTENT_APPLICATION_DATA, message, 4u,
                         first, &first_length) &&
        !tls_record_seal(&repeated, TLS_CONTENT_APPLICATION_DATA, message, 4u,
                         second, &second_length) &&
        first_length == second_length &&
        !crypto_equal(first, second, first_length);

    // A wrapped counter would repeat a nonce, which hands an attacker the
    // GHASH key. The connection has to die instead.
    struct tls_record_context exhausted;
    valid = valid && !tls_record_init(&exhausted, rfc_client_application);
    exhausted.sequence = 0xFFFFFFFFFFFFFFFFull;
    valid = valid &&
        tls_record_seal(&exhausted, TLS_CONTENT_APPLICATION_DATA, message, 4u,
                        record, &record_length) == -1 &&
        tls_record_seal(&exhausted, TLS_CONTENT_APPLICATION_DATA, message, 4u,
                        record, &record_length) == -1 &&
        tls_record_open(&exhausted, rfc_record, sizeof(rfc_record), plaintext,
                        &plaintext_length, &content_type) == -1;

    // Malformed framing, checked before any decryption is attempted.
    struct tls_record_context guard;
    valid = valid && !tls_record_init(&guard, rfc_server_handshake) &&
        tls_record_open(&guard, rfc_record, TLS_RECORD_HEADER_SIZE, plaintext,
                        &plaintext_length, &content_type) == -1 &&
        tls_record_open(&guard, rfc_record, sizeof(rfc_record) - 1u,
                        plaintext, &plaintext_length, &content_type) == -1 &&
        tls_record_seal(&guard, TLS_CONTENT_APPLICATION_DATA, message,
                        TLS_RECORD_MAX_PLAINTEXT + 1u, record,
                        &record_length) == -1;

    // Bad arguments to the label encoder, which is the one place a caller
    // could otherwise overrun a buffer.
    u8 scratch[TLS_SECRET_SIZE];
    valid = valid &&
        tls_hkdf_expand_label(rfc_master_secret, "", 0, 0, scratch,
                              TLS_SECRET_SIZE) == -1 &&
        tls_hkdf_expand_label(rfc_master_secret,
                              "a label far longer than the protocol permits",
                              0, 0, scratch, TLS_SECRET_SIZE) == -1 &&
        tls_hkdf_expand_label(0, "key", 0, 0, scratch, TLS_SECRET_SIZE) == -1;

    tls_key_schedule_clear(&schedule);
    valid = valid && !schedule.master_secret[0] &&
        !schedule.master_secret[TLS_SECRET_SIZE - 1u];
    return valid ? 0 : -1;
}
